function attributesToMarkup(attributes, { mask = false } = {}) {
  return Object.entries(attributes).map(([name, value]) => {
    const normalized = mask && value === "currentColor" ? "#000" : value;
    return `${name}="${normalized}"`;
  }).join(" ");
}

// SidebarTabExtension currently accepts an icon-class string rather than an
// SVG node. A CSS mask lets the adapter keep using that public API while the
// visible glyph still comes from this local Icon Kit and inherits currentColor.
export function workspaceKitIconMaskDataUri(iconKey) {
  const definition = iconDefinitions[iconKey];
  if (!definition) throw new RangeError(`Unknown WorkspaceKit icon: ${String(iconKey)}`);
  const shapes = Array.isArray(definition)
    ? definition.map(([tagName, attributes]) => `<${tagName} ${attributesToMarkup(attributes, { mask: true })}/>`).join("")
    : definition.markup.replaceAll("currentColor", "#000");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

export function createWorkspaceKitIcon(document, iconKey, { size = 18, className = "" } = {}) {
  if (!document?.createElementNS) throw new TypeError("WorkspaceKit icons require a document with createElementNS().");
  const definition = iconDefinitions[iconKey];
  if (!definition) throw new RangeError(`Unknown WorkspaceKit icon: ${String(iconKey)}`);
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.dataset.workspacekitIcon = iconKey;
  svg.className.baseVal = ["workspacekit-ui-icon", className].filter(Boolean).join(" ");
  if (Array.isArray(definition)) {
    for (const [tagName, attributes] of definition) {
      const element = document.createElementNS("http://www.w3.org/2000/svg", tagName);
      for (const [name, value] of Object.entries(attributes)) element.setAttribute(name, value);
      svg.append(element);
    }
  } else {
    svg.innerHTML = definition.markup;
  }
  return svg;
}
